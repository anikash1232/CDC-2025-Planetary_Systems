// Calculate stats
const validGFractions = STATIC_EXOPLANETS.filter(p => p.g_fraction !== null).map(p => p.g_fraction!)
const validMasses = STATIC_EXOPLANETS.filter(p => p.pl_bmasse !== null).map(p => p.pl_bmasse!)
const validRadii = STATIC_EXOPLANETS.filter(p => p.pl_rade !== null).map(p => p.pl_rade!)

export const STATIC_STATS: StaticStats = {
  total_planets: 190,
  g_fraction_range: {
    min: Math.min(...validGFractions),
    max: Math.max(...validGFractions),
    mean: validGFractions.reduce((a, b) => a + b, 0) / validGFractions.length
  },
  intensity_index_distribution: STATIC_EXOPLANETS.reduce((acc, p) => {
    if (p.intensity_index !== null) {
      const key = p.intensity_index.toString()
      acc[key] = (acc[key] || 0) + 1
    }
    return acc
  }, {} as Record<string, number>),
  mass_range: {
    min: Math.min(...validMasses),
    max: Math.max(...validMasses),
    mean: validMasses.reduce((a, b) => a + b, 0) / validMasses.length
  },
  radius_range: {
    min: Math.min(...validRadii),
    max: Math.max(...validRadii),
    mean: validRadii.reduce((a, b) => a + b, 0) / validRadii.length
  }
}

// Helper function to get random subset of static data
export function getRandomStaticPlanets(limit: number = 200): StaticExoplanet[] {
  const shuffled = [...STATIC_EXOPLANETS].sort(() => 0.5 - Math.random())
  return shuffled.slice(0, Math.min(limit, STATIC_EXOPLANETS.length))
}

// Helper function to search static data
export function searchStaticPlanets(query: string, limit: number = 200): StaticExoplanet[] {
  if (!query.trim()) {
    return getRandomStaticPlanets(limit)
  }
  
  const searchTerm = query.toLowerCase()
  const filtered = STATIC_EXOPLANETS.filter(planet => 
    planet.pl_name.toLowerCase().includes(searchTerm) ||
    planet.hostname.toLowerCase().includes(searchTerm)
  )
  
  return filtered.slice(0, limit)
}
